import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';

const ROOT = resolve(import.meta.dirname, '../..');

test('index.html is a scrollable project homepage that embeds the app', () => {
    const html = readFileSync(resolve(ROOT, 'index.html'), 'utf8');
    const css = readFileSync(resolve(ROOT, 'src/project-home.css'), 'utf8');
    const js = readFileSync(resolve(ROOT, 'src/project-home.js'), 'utf8');

    assert.match(html, /<title>Humanoid Jog Lab<\/title>/);
    assert.match(html, /<link rel="stylesheet" href="\/src\/project-home.css">/);
    assert.match(html, /class="hero"/);
    assert.match(html, /class="publication-title"/);
    assert.match(html, /class="link-block"/);
    const linkBlock = html.match(/<div class="link-block" aria-label="Project links">([\s\S]*?)<\/div>/)?.[1] || '';
    assert.match(html, /Code \(coming soon\)/);
    assert.match(html, /href="https:\/\/youtu\.be\/EpACglMYUrI"[^>]*>Video<\/a>/);
    assert.match(html, /target="_blank"/);
    assert.match(html, /rel="noopener noreferrer"/);
    assert.match(html, /href="#interactive-demo"/);
    assert.doesNotMatch(linkBlock, /Open full demo/);
    assert.doesNotMatch(html, /class="project-nav"/);
    assert.doesNotMatch(html, /aria-label="Project sections"/);
    assert.doesNotMatch(html, /Interactive Robotics Project/);
    assert.doesNotMatch(html, /A project website and interactive browser demo/);
    assert.doesNotMatch(html, /class="publication-subtitle"/);
    assert.doesNotMatch(html, /class="author-line"/);
    assert.doesNotMatch(html, /href="#method"/);
    assert.match(html, /<section class="section youtube-section" id="project-video">/);
    assert.match(html, /<p class="section-kicker">Project Video<\/p>/);
    assert.match(html, /class="youtube-frame-shell"/);
    assert.match(html, /<iframe[\s\S]*src="https:\/\/www\.youtube\.com\/embed\/EpACglMYUrI\?si=JDVWW2aEDl3XpG1Q"[\s\S]*title="YouTube video player"[\s\S]*allowfullscreen[\s\S]*><\/iframe>/);
    assert.match(html, /id="video"/);
    assert.match(html, /class="video-grid"/);
    assert.match(html, /<p class="section-kicker">Hardware Demonstrations<\/p>/);
    assert.doesNotMatch(html, /<h2>Semantic-Preserving Jog Teaching<\/h2>/);
    assert.doesNotMatch(html, /Three hardware clips show the constraint-aware controller/);
    assert.match(html, /\/videos\/video1\.mp4[\s\S]+Box grasping/);
    assert.match(html, /\/videos\/video3\.mp4[\s\S]+Box carrying/);
    assert.match(html, /\/videos\/video2\.mp4[\s\S]+Curved-surface polishing/);
    const projectVideoTags = html.match(/<video\s+[^>]*class="project-video"[^>]*>/g) || [];
    assert.equal(projectVideoTags.length, 3);
    projectVideoTags.forEach((videoTag) => {
        assert.doesNotMatch(videoTag, /\scontrols(?:\s|>|=)/);
        assert.match(videoTag, /\sautoplay/);
        assert.match(videoTag, /\smuted/);
        assert.match(videoTag, /\splaysinline/);
        assert.match(videoTag, /\sdata-smooth-loop/);
        assert.match(videoTag, /data-loop-start="0\.06"/);
        assert.match(videoTag, /data-loop-end-offset="0\.22"/);
        assert.doesNotMatch(videoTag, /\sloop(?:\s|=|>)/);
    });
    assert.match(html, /<script type="module" src="\/src\/project-home\.js"><\/script>/);
    assert.match(html, /poster="\/images\/video1-poster\.jpg"/);
    assert.match(html, /poster="\/images\/video2-poster\.jpg"/);
    assert.match(html, /poster="\/images\/video3-poster\.jpg"/);
    assert.doesNotMatch(html, /humanoid-jog-demo\.mp4/);
    assert.match(html, /id="abstract"/);
    const abstractSection = html.match(/<section class="section abstract-section" id="abstract">([\s\S]*?)<\/section>/)?.[1] || '';
    assert.match(abstractSection, /<p class="section-kicker">Abstract<\/p>/);
    assert.doesNotMatch(abstractSection, /<h2>/);
    assert.doesNotMatch(abstractSection, /Paper Abstract/);
    assert.equal((abstractSection.match(/<p(?:\s|>)/g) || []).length, 2);
    assert.match(html, /Constrained Cooperative Task-Space Manipulability for Semantic-Preserving Humanoid Jog Teaching/);
    assert.match(html, /This paper studies humanoid upper-body cooperative jog teaching from the viewpoint of\s+constraint-aware manipulability and semantic-preserving local control\./);
    assert.match(html, /Simulations and hardware demonstrations validate the resulting\s+semantic preservation, constraint handling, and boundary-aware manipulability behavior\./);
    assert.doesNotMatch(html, /id="results"/);
    assert.doesNotMatch(html, /Experiment Hooks/);
    assert.doesNotMatch(html, />Results</);
    assert.match(html, /id="interactive-demo"/);
    const demoSection = html.match(/<section class="section demo-section" id="interactive-demo">([\s\S]*?)<\/section>/)?.[1] || '';
    assert.match(demoSection, /<p class="section-kicker">Interactive Demo<\/p>/);
    assert.doesNotMatch(demoSection, /<h2>/);
    assert.doesNotMatch(demoSection, /Embedded Humanoid Jog Lab/);
    assert.doesNotMatch(demoSection, /The full controller UI is embedded below/);
    assert.match(html, /<iframe[^>]+src="\/app.html"[^>]+title="Humanoid Jog Lab interactive demo"/s);
    assert.match(html, /href="\/app.html"[^>]*>Open full demo</);
    assert.doesNotMatch(html, /Citation/i);
    assert.doesNotMatch(html, /href="#paper"/);
    assert.doesNotMatch(html, /<section class="section paper-section" id="paper">/);
    assert.doesNotMatch(html, /<pre>/);
    assert.doesNotMatch(html, /@misc/);
    assert.doesNotMatch(html, /id="robot-canvas"/);
    assert.doesNotMatch(html, /id="control-panel"/);
    assert.doesNotMatch(html, /id="method"/);
    assert.doesNotMatch(html, /class="method-grid"/);
    assert.doesNotMatch(html, />Method</);
    assert.doesNotMatch(html, /class="site-footer"/);
    assert.doesNotMatch(html, />Humanoid Jog Lab<\/span>/);
    assert.doesNotMatch(html, />Interactive app</);
    assert.doesNotMatch(css, /result-strip/);
    assert.doesNotMatch(css, /site-footer/);
    assert.doesNotMatch(css, /project-nav/);
    assert.match(css, /\.hero\s*\{[\s\S]*min-height: auto;/);
    assert.match(css, /\.hero\s*\{[\s\S]*padding: 48px 24px 36px;/);
    assert.match(css, /\.youtube-section\s*\{[\s\S]*padding: 24px 0 20px;/);
    assert.match(css, /\.youtube-frame-shell\s*\{[\s\S]*aspect-ratio: 16 \/ 9;/);
    assert.match(css, /\.youtube-frame-shell iframe\s*\{[\s\S]*width: 100%;[\s\S]*height: 100%;/);
    assert.match(css, /\.video-section\s*\{[\s\S]*padding: 12px 0 24px;/);
    assert.match(css, /\.abstract-section\s*\{[\s\S]*padding: 16px 0 12px;/);
    assert.match(css, /\.abstract-section \.narrow-copy p:last-child\s*\{[\s\S]*margin-bottom: 0;/);
    assert.match(css, /\.demo-section\s*\{[\s\S]*padding: 8px 0 64px;/);
    assert.doesNotMatch(css, /paper-section/);
    assert.match(css, /@media \(max-width: 820px\)[\s\S]*\.hero\s*\{[\s\S]*padding: 40px 16px 30px;/);
    assert.match(css, /@media \(max-width: 820px\)[\s\S]*\.youtube-section\s*\{[\s\S]*padding: 18px 0 16px;/);
    assert.match(css, /@media \(max-width: 820px\)[\s\S]*\.video-section\s*\{[\s\S]*padding: 12px 0 18px;/);
    assert.match(css, /@media \(max-width: 820px\)[\s\S]*\.abstract-section\s*\{[\s\S]*padding: 14px 0 10px;/);
    assert.match(css, /@media \(max-width: 820px\)[\s\S]*\.demo-section\s*\{[\s\S]*padding: 8px 0 52px;/);
    assert.doesNotMatch(css, /publication-subtitle/);
    assert.doesNotMatch(css, /author-line/);
    assert.match(css, /\.publication-title\s*\{[\s\S]*font-size: clamp\(2\.1rem, 4vw, 3\.4rem\);/);
    assert.match(css, /@media \(max-width: 820px\)[\s\S]*\.publication-title\s*\{[\s\S]*font-size: clamp\(1\.85rem, 8vw, 2\.45rem\);/);
    assert.match(js, /requestVideoFrameCallback/);
    assert.match(js, /duration - loopEndOffset/);
    assert.match(js, /video\.currentTime = loopStart/);
});

test('app.html keeps the full interactive robot application entry point', () => {
    const html = readFileSync(resolve(ROOT, 'app.html'), 'utf8');

    assert.match(html, /<canvas id="robot-canvas"><\/canvas>/);
    assert.match(html, /id="control-panel"/);
    assert.match(html, /id="humanoid-jog-solver-select"/);
    assert.match(html, /<script type="module" src="\/src\/main.js"><\/script>/);
});
